import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(
  await readFile(path.join(root, "package.json"), "utf8"),
);
import { bundle } from './bundle.mjs';
// Local declarations may span several lines after formatting. External SDK and
// React imports remain intact in the generated plugin.
// "catalog" variant: Whole window only. Drops everything between @chat-area
// markers (the rules that restyle the app's own markup) for catalog rule 8.
const catalog = process.argv.includes("--catalog");
const outArg = process.argv.indexOf("--out");
if (outArg > -1 && (!process.argv[outArg + 1] || process.argv[outArg + 1].startsWith('--'))) throw Error('--out requires a file path');
const outFile = outArg > -1 ? path.resolve(process.argv[outArg + 1]) : path.join(root, "desktop/plugin.js");
if (!outFile.endsWith('.js')) throw Error('--out must name a .js bundle');
const relativeOut=path.relative(root,outFile).split(path.sep).join('/');
if(['src/','scripts/','tests/'].some(p=>relativeOut.startsWith(p))) throw Error('--out cannot overwrite project source or tests');
const variant = (source) =>
  catalog
    ? source
        .replace(/[ \t]*\/\/ @chat-area:begin[\s\S]*?\/\/ @chat-area:end\n/g, "")
        .replace(/[ \t]*<!-- @chat-area:begin -->[\s\S]*?<!-- @chat-area:end -->\n/g, "")
        .replace("const CHAT_AREA = true;", "const CHAT_AREA = false;")
    : source;
const adapter = await bundle(root, 'src/plugin.js', variant);
const core = catalog || outArg > -1 ? '' : await bundle(root, 'src/world.js', variant);
await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  `// ASCII Worlds v${version} | MIT | Generated by npm run ${catalog ? "build:catalog (Whole window only)" : "build"}\n${adapter}\nexport default __entry.default;\n`,
);
if (catalog || outArg > -1) {
  console.log('Built alternate plugin bundle (demo.html not touched).');
  process.exit(0);
}
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark"><title>ASCII Worlds — living studies</title>
<style>html,body{margin:0;width:100%;height:100%;background:Canvas;color:CanvasText}.chat-demo [data-chat-surface]{flex:1;align-self:stretch;padding:32px;max-width:560px;background:Canvas}.chat-demo [data-slot=aui_thread-viewport]{background:Canvas}.chat-demo #world{max-width:420px}.who{font-size:11px;text-transform:uppercase;letter-spacing:.1em;opacity:.65}body{display:flex;justify-content:center;align-items:center;font-family:system-ui}#world{height:100%;width:100%;max-width:1440px;min-height:0;overflow:auto}*{box-sizing:border-box}</style></head>
<body><main id="world"></main><script type="module">
${core}
const {mountWorld}=__entry;
const {browserStorage}=__modules['src/settings.js'];
const {createHub,createBackgroundHost}=__modules['src/background.js'];
const params=new URLSearchParams(location.search);
// Optional fake-chat demo of Background mode: ?chat=1 (this page is not Hermes Desktop).
let hub=null;
if(params.has('chat')){hub=createHub(browserStorage());document.body.classList.add('chat-demo');const chat=document.createElement('section');chat.setAttribute('data-chat-surface','');chat.innerHTML='<div data-slot="aui_thread-viewport"><p class="who">You</p><p>What is moving behind this conversation?</p><p class="who">Assistant</p><p>A quiet pond of glyphs. Switch the background on in the settings or with the button below; strength is adjustable and the same switch turns it off again.</p><button type="button" id="bgtoggle">Toggle background</button></div>';document.body.prepend(chat);const host=createBackgroundHost({hub});host.attach();document.getElementById('bgtoggle').onclick=()=>host.toggle();window.asciiWorldsBackground={host,hub};}
const world=mountWorld(document.getElementById('world'),browserStorage(),hub);
// Public, demo-only deterministic inspection API. No host state is exposed.
window.asciiWorlds={get settings(){return world.settings;},get stats(){return world.stats;},setSettings:patch=>world.setSettings(patch),renderAt:(seconds,beat)=>world.renderAt(seconds,beat),resume:()=>world.resume(),reset:()=>world.reset(),resetScene:()=>world.resetScene(),destroy:()=>world.destroy()};
const patch={};for(const key of ['scene','palette','density','colour','tint'])if(params.has(key))patch[key]=params.get(key);
if(params.has('paused'))patch.paused=params.get('paused')!=='false';
if(Object.keys(patch).length)world.setSettings(patch);
if(params.has('time'))world.renderAt(Number(params.get('time')));
</script></body></html>`;
await writeFile(path.join(root, "demo.html"), html);
console.log(
  "Built desktop/plugin.js and demo.html (no dependencies).",
);
