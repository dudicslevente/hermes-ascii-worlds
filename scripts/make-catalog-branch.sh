#!/usr/bin/env bash
# Creates or refreshes the `catalog` branch: the same plugin without the Chat
# area placement (which restyles Hermes Desktop's own markup, catalog rule 8).
#
#   scripts/make-catalog-branch.sh          # build and commit locally
#   scripts/make-catalog-branch.sh --push   # also push the branch
#
# The branch is main plus one generated commit: desktop/plugin.js is rebuilt
# with `npm run build:catalog`, and the README drops everything between
# chat-area markers and shows the catalog-only text instead. This script never
# opens a pull request.
set -euo pipefail
cd "$(dirname "$0")/.."
if [ -n "$(git status --porcelain)" ]; then
  echo "Working tree is not clean; commit or stash first." >&2
  exit 1
fi
start=$(git rev-parse --abbrev-ref HEAD)
trap 'git checkout -q "$start"' EXIT
git checkout -q -B catalog main
npm run build:catalog >/dev/null
node scripts/catalog-readme.mjs
git add -A
if git diff --cached --quiet; then
  echo "catalog branch already up to date"
else
  git commit -q -m "Catalog build: Whole window placement only" \
    -m "Generated by scripts/make-catalog-branch.sh. Removes the Chat area placement, which restyles the app's own markup (catalog rule 8)."
fi
git rev-parse HEAD
if [ "${1:-}" = "--push" ]; then
  git push --force-with-lease origin catalog
fi
