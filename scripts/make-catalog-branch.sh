#!/usr/bin/env bash
# Creates or refreshes the `catalog` branch: the same plugin without the Chat
# area placement (which restyles Hermes Desktop's own markup, catalog rule 8).
#
#   scripts/make-catalog-branch.sh          # build and commit locally
#   scripts/make-catalog-branch.sh --push   # also push the branch (fast-forward only)
#
# The tree is main plus the generated catalog build: desktop/plugin.js is rebuilt
# with `npm run build:catalog`, and the README and linked docs drop everything
# between chat-area markers and show the catalog-only text instead. The new commit
# is added on top of the previous catalog tip, because a Hermes catalog entry can
# pin that commit and it has to stay reachable; main becomes a second parent when
# the previous tip does not contain it yet. Catalog history is only ever extended:
# this script never rewrites or force-pushes it, never switches your checked-out
# branch and never opens a pull request.
set -euo pipefail
cd "$(dirname "$0")/.."
push=false
[ "$#" -le 1 ] || { echo "usage: $0 [--push]" >&2; exit 2; }
case "${1:-}" in
  "") ;;
  --push) push=true ;;
  *) echo "usage: $0 [--push]" >&2; exit 2 ;;
esac
if [ -n "$(git status --porcelain)" ]; then
  echo "Working tree is not clean; commit or stash first." >&2
  exit 1
fi
if [ "$(git rev-parse --abbrev-ref HEAD)" = "catalog" ]; then
  echo "Switch to another branch first; the catalog branch is updated in place." >&2
  exit 1
fi
main=$(git rev-parse --verify main)
local_tip=$(git rev-parse --verify --quiet refs/heads/catalog || true)
prev=${local_tip:-$(git rev-parse --verify --quiet refs/remotes/origin/catalog || true)}
work=$(mktemp -d "${TMPDIR:-/tmp}/ascii-worlds-catalog.XXXXXX")
trap 'git worktree remove --force "$work" >/dev/null 2>&1 || { rm -rf "$work"; git worktree prune; }' EXIT
git worktree add -q --detach "$work" "$main"
tree=$(cd "$work" && npm run build:catalog >/dev/null && node scripts/catalog-readme.mjs >/dev/null && git add -u && git write-tree)
if [ -n "$prev" ] && [ "$(git rev-parse "$prev^{tree}")" = "$tree" ]; then
  echo "catalog branch already up to date" >&2
  commit=$prev
else
  parents=()
  if [ -n "$prev" ]; then
    parents+=(-p "$prev")
    git merge-base --is-ancestor "$main" "$prev" || parents+=(-p "$main")
  else
    parents+=(-p "$main")
  fi
  commit=$(git commit-tree "$tree" "${parents[@]}" \
    -m "Catalog build: Whole window placement only" \
    -m "Generated by scripts/make-catalog-branch.sh. Removes the Chat area placement, which restyles the app's own markup (catalog rule 8).")
fi
if [ "$commit" != "${local_tip:-}" ]; then
  git update-ref -m "catalog build" refs/heads/catalog "$commit" "${local_tip:-}"
fi
echo "$commit"
if [ "$push" = true ]; then
  git push origin refs/heads/catalog:refs/heads/catalog
fi
